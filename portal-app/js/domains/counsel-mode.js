/**
 * CounselMode — 悩み・迷いの相談に乗っている間だけ、深掘りを許す（相談モード）
 *
 * 背景: 応答スタイルの規律（1回3文以内／掘り下げは連続2回まで／閉じ系返信が多いと2文以内）は
 * 通常の雑談・依頼には効くが、悩みの相談では「2往復で会話が終わる」原因になっていた。
 * card.json の「思考ガイド機能」（受容→反転の問い→分解→静寂）を活かすには、その間だけ
 * 上記の規律を緩める必要がある。
 *
 * 「プロンプトに書いた規律は守られない」（docs/architecture/conversation.md）ので、
 * 相談かどうかの判定と緩和の範囲はコード側（このファイル）で確定させ、AI には結果の指示だけを渡す。
 *
 * 判定は語彙による近似。外れたときの被害は「深掘りが始まらない」か「余計に1〜2文長くなる」だけで小さい。
 */
const CounselMode = {
  /** 相談モードで許す往復の目安。これを超えたら整理して締めるよう促す */
  MAX_TURNS: 6,

  _active: false,
  _turns: 0,

  // 悩み・迷い・気持ちの重さを示す語（人格に依らずユーザー側の言葉なので、パックではなくここに置く）
  TOPIC: /悩|迷[いっう]|相談|不安|しんどい|しんどく|つらい|辛い|モヤモヤ|もやもや|どうしたら|どうすれば|決められ|決まらない|落ち込|憂鬱|うまくいかな|上手くいかな|向いてない/,

  // 会話を閉じる短い言葉（先頭一致・短文のときだけ）
  CLOSE: /^(ありがと|ありがとう|サンキュ|了解|りょうかい|わかった|分かった|ok|OK|おっけ|大丈夫やで|バイバイ|おやすみ|また明日|もういい|ここまで|助かった)/,

  get active() { return this._active; },
  get turns() { return this._turns; },

  reset() { this._active = false; this._turns = 0; },

  /**
   * ユーザー発話のたびに呼び、モードの入り・継続・終了を更新する。
   * @param {string} text ユーザーの発話
   * @param {boolean} viaButton 「日記に書く」等の定型ボタン経由か（判定に使わない）
   */
  update(text, viaButton = false) {
    if (viaButton) return;
    const t = String(text || '').trim();
    if (!t) return;

    if (t.length <= 20 && this.CLOSE.test(t)) { this.reset(); return; }

    if (this.TOPIC.test(t)) {
      if (!this._active) { this._active = true; this._turns = 0; }
    }
    if (this._active) this._turns++;
  },

  /** 整理して締めるべき段階か */
  get shouldWrapUp() { return this._active && this._turns > this.MAX_TURNS; },

  /**
   * 相談モード中だけシステムプロンプトへ足すブロック。応答スタイルの節より優先させる。
   * @returns {string} 相談モードでなければ空文字
   */
  promptBlock() {
    if (!this._active) return '';
    const wrap = this.shouldWrapUp
      ? '- すでに十分に深掘りしました。**次の返答では新しい質問をせず**、話の要点を1〜2文でまとめ、次の一歩を1つだけ提案し、日記に残すか一言聞いてください。'
      : `- 目安は${this.MAX_TURNS}往復までです。答えを急がず、ユーザー自身が気持ちと状況を整理できるよう促してください。`;

    return `## 相談モード（いま、ユーザーは悩み・迷いを話しています。この節は「応答スタイル」より優先する）
- 人格設定の「思考ガイド機能」に沿って、すぐ答えを出さず、深掘りしてください。
- **この間は「掘り下げの問いかけは連続2回まで」の制限を適用しません。**「質問を質問で返さない」も、情報を求められたときの規則です。相手の気持ちや状況を引き出す質問は、してかまいません。
- 1回の返答は3文以内（1文は短く）。**質問は1返答につき1つだけ**にして、畳みかけない。
- 順序の目安（会話の流れで今どこかを判断する）:
  1. 受け止める: 一般論で片付けず、何がしんどいのかに具体的に触れる
  2. 事実と気持ちを分けて聞く（何があったか／どう感じているか）
  3. 反転の問い、または問題を小さく分解する
  4. 小さな次の一歩、または「5分だけ考えてみよか」の提案
- ユーザーが情報や選択肢を明確に求めたときは、先に内容で答えてから、必要なら1つ聞く。
- 返信候補は会話を閉じる言葉ではなく、続きを話しやすい言葉にする（例:「実はな…」「整理したい」「もう少し聞いて」）。各12文字以内。
${wrap}
- ユーザーが「ありがとう」等で会話を閉じたら、蒸し返さず短く締める。`;
  }
};

window.CounselMode = CounselMode;
